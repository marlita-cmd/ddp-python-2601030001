# Latihan 3: Konversi suhu Celsius ke Fahrenheit dan Kelvin

# Menyimpan suhu dalam Celsius
suhu_celsius = 25

# Menghitung konversi suhu
suhu_fahrenheit = (suhu_celsius * 9 / 5) + 32
suhu_kelvin = suhu_celsius + 273.15

# Menampilkan hasil
print("=== KONVERSI SUHU ===")
print(f"Celsius    : {suhu_celsius} C")
print(f"Fahrenheit : {suhu_fahrenheit} F")
print(f"Kelvin     : {suhu_kelvin} K")